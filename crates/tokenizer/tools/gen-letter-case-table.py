#!/usr/bin/env python3
"""Generate src/letter_case_table.rs from Unicode 14.0's UnicodeData.txt.

Hugging Face's tokenizers matches a regex with Oniguruma 6.9.8, whose tables are Unicode 14.0's. A pre-tokenizer regex
that tells `\\p{Lu}`, `\\p{Lt}`, `\\p{Ll}`, `\\p{Lm}` and `\\p{Lo}` apart (MiniMax's) needs the general category of every
letter, which the reference's collapsed byte (`collapse_table.rs`, one byte for all letters) does not carry. This
table gives each codepoint >= 0x80 one of four values:

    0  not a letter in Unicode 14.0
    1  Lu or Lt   (upper: `[\\p{Lu}\\p{Lt}...]`)
    2  Ll         (lower)
    3  Lm or Lo   (both classes)

Usage:

    python3 gen-letter-case-table.py <UnicodeData.txt of 14.0.0> > ../src/letter_case_table.rs
"""
import hashlib
import sys

MAX = 0x110000
CLASS = {"Lu": 1, "Lt": 1, "Ll": 2, "Lm": 3, "Lo": 3}


def main():
    raw = open(sys.argv[1], "rb").read()
    cls = bytearray(MAX)
    first = None
    for line in raw.decode("ascii").splitlines():
        fields = line.split(";")
        cp, name, cat = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
            continue
        lo = first if name.endswith(", Last>") else cp
        first = None
        cls[lo:cp + 1] = bytes([CLASS.get(cat, 0)]) * (cp + 1 - lo)
    runs = [(cp, cls[cp]) for cp in range(0x80, MAX) if cp == 0x80 or cls[cp] != cls[cp - 1]]
    print("// @generated by tools/gen-letter-case-table.py from Unicode 14.0.0's UnicodeData.txt (md5 %s)." % hashlib.md5(raw).hexdigest())
    print("// Do not edit by hand. The data is the Unicode Consortium's, under the Unicode License;")
    print("// the full notice is in THIRD_PARTY_NOTICES.md at the repository root.")
    print()
    print("/// `(first codepoint, case class)` for every run of codepoints >= 0x80 that share a class (0 not a letter, 1 Lu or")
    print("/// Lt, 2 Ll, 3 Lm or Lo); a run ends where the next one starts, the last one at 0x110000.")
    print("pub(crate) static RUNS: [(u32, u8); %d] = [" % len(runs))
    for cp, c in runs:
        print("    (0x%06X, %d)," % (cp, c))
    print("];")


if __name__ == "__main__":
    main()
